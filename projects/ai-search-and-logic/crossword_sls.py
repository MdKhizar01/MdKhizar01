import random

WORDS = """
at eta be hat he her it him on one desk dance usage easy dove
first else loses fuels help haste given kind sense soon sound this think
""".split()

# Each slot: (starting row, starting column, direction, length).
# Coordinates start at zero. A = across; D = down.
SLOTS = {
    "1A": (0, 1, "A", 4),
    "1D": (0, 1, "D", 5),
    "2D": (0, 2, "D", 3),
    "3A": (1, 1, "A", 2),
    "4A": (2, 0, "A", 5),
    "5D": (2, 3, "D", 5),
    "6A": (4, 1, "A", 4),
}

# Each variable can use only words matching its slot length.
DOMAINS = {
    variable: [word for word in WORDS if len(word) == slot[3]]
    for variable, slot in SLOTS.items()
}


def cells(slot):
    """Return the ordered coordinates occupied by a word slot."""
    row, col, direction, length = slot
    return [
        (
            row + (i if direction == "D" else 0),
            col + (i if direction == "A" else 0),
        )
        for i in range(length)
    ]


def build_constraints():
    """
    Generate constraints at intersections.

    (x, i, y, j) means assignment[x][i] == assignment[y][j].
    """
    constraints = []
    names = list(SLOTS)

    for p, x in enumerate(names):
        for y in names[p + 1:]:
            for i, cell_x in enumerate(cells(SLOTS[x])):
                for j, cell_y in enumerate(cells(SLOTS[y])):
                    if cell_x == cell_y:
                        constraints.append((x, i, y, j))

    return constraints


CONSTRAINTS = build_constraints()


def conflicts(assignment):
    """Return the violated intersection constraints."""
    return [
        (x, i, y, j)
        for x, i, y, j in CONSTRAINTS
        if assignment[x][i] != assignment[y][j]
    ]


def solve(
    seed=42,
    noise=0.20,
    max_steps=2000,
    max_tries=50,
    verbose=True,
):
    """
    Any-conflict stochastic local search.

    Select a random conflict and then a random variable in it.
    Choose either a random alternative word or an alternative
    minimizing the total number of conflicts.
    """
    rng = random.Random(seed)
    moves = 0

    for attempt in range(1, max_tries + 1):
        assignment = {
            variable: rng.choice(DOMAINS[variable])
            for variable in SLOTS
        }

        if verbose:
            print(
                f"Try {attempt}: initial conflicts = "
                f"{len(conflicts(assignment))}"
            )

        for step in range(max_steps + 1):
            violated = conflicts(assignment)

            if not violated:
                return assignment, attempt, moves

            if step == max_steps:
                break

            # Select a random violated constraint.
            x, _, y, _ = rng.choice(violated)

            # Select one of its variables randomly.
            variable = rng.choice((x, y))
            old_word = assignment[variable]

            # Each move changes exactly one word.
            candidates = [
                word
                for word in DOMAINS[variable]
                if word != old_word
            ]

            if rng.random() < noise:
                new_word = rng.choice(candidates)
                mode = "random"
            else:
                best_score = float("inf")
                best_words = []

                for word in candidates:
                    assignment[variable] = word
                    score = len(conflicts(assignment))

                    if score < best_score:
                        best_score = score
                        best_words = [word]
                    elif score == best_score:
                        best_words.append(word)

                # Break ties randomly.
                new_word = rng.choice(best_words)
                mode = "min-conflicts"

            assignment[variable] = new_word
            moves += 1

            # Show the first ten moves of each try and the final move.
            if verbose and (step < 10 or not conflicts(assignment)):
                print(
                    f"  Move {moves}: {variable} "
                    f"{old_word} -> {new_word} ({mode}); "
                    f"conflicts = {len(conflicts(assignment))}"
                )

    return None, max_tries, moves


def validate(assignment):
    """Check completeness, word membership, and intersections."""
    assert set(assignment) == set(SLOTS), "Missing or extra variables"

    assert all(
        assignment[v] in DOMAINS[v] for v in SLOTS
    ), "Invalid word"

    assert not conflicts(assignment), "An intersection does not match"


def print_grid(assignment):
    """Display the irregular puzzle in a rectangular frame."""
    grid = [["#"] * 5 for _ in range(7)]

    for variable, word in assignment.items():
        for (row, col), letter in zip(cells(SLOTS[variable]), word):
            assert grid[row][col] in ("#", letter)
            grid[row][col] = letter

    for row in grid:
        print(" ".join(row).upper())


def main():
    print("PA2 - Crossword Figure 4.15(b)")
    print("Algorithm: Any-conflict stochastic local search")
    print("Seed: 42 | Noise: 0.20 | Steps per try: 2000 | Tries: 50")

    print(
        f"Variables: {len(SLOTS)} | "
        f"Constraints: {len(CONSTRAINTS)}"
    )

    print("\nDomains:")
    for variable in SLOTS:
        print(f"  {variable}: {', '.join(DOMAINS[variable])}")

    print("\nExecution trace:")
    solution, tries, moves = solve()

    if solution is None:
        print("No solution found within the search budget.")
        print("This does not prove that the CSP is unsatisfiable.")
        return

    validate(solution)

    print(f"\nSOLUTION FOUND | Tries: {tries} | Moves: {moves}")
    for variable in SLOTS:
        print(f"  {variable} = {solution[variable]}")

    print("\nCompleted crossword (# = blocked or outside cell):")
    print_grid(solution)

    print("\nValidation: all words legal; all intersections match.")
    print("Final conflicts: 0")

    # Repeat the search using seeds 0 through 99.
    successes = 0
    move_counts = []

    for seed in range(100):
        result, _, count = solve(seed=seed, verbose=False)

        if result is not None:
            validate(result)
            successes += 1
            move_counts.append(count)

    print(f"\n100-seed experiment: {successes}/100 successful runs")

    if move_counts:
        print(
            f"Moves among successful runs: "
            f"min={min(move_counts)}, "
            f"max={max(move_counts)}, "
            f"mean={sum(move_counts) / len(move_counts):.2f}"
        )


if __name__ == "__main__":
    main()
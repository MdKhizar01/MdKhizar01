KB = [
    ("a", ("b", "c")),
    ("b", ("d",)),
    ("b", ("e",)),
    ("c", ()),
    ("d", ("h",)),
    ("e", ()),
    ("f", ("g", "b")),
    ("g", ("c", "k")),
    ("j", ("a", "b")),
]


def clause_text(head, body):
    """Return a readable representation of a clause."""
    if body:
        return f"{head} <- {' & '.join(body)}"
    return f"{head} (fact)"


def set_text(atoms):
    """Display atoms in alphabetical order."""
    return "{" + ", ".join(sorted(atoms)) + "}"


def bottom_up(kb, verbose=True):
    """
    Forward chaining in rounds.

    Each round uses only the atoms known before that round.
    Stop when no new atom can be derived.
    """
    known = set()
    round_number = 0

    while True:
        additions = {}

        for head, body in kb:
            if head not in known and all(
                atom in known for atom in body
            ):
                additions.setdefault(head, body)

        if not additions:
            if verbose:
                print(
                    "Fixed point reached: "
                    "no new atoms can be derived."
                )
            return known

        round_number += 1

        if verbose:
            print(f"Round {round_number}:")
            for head, body in additions.items():
                print(
                    f"  Derive {head} using "
                    f"{clause_text(head, body)}"
                )

        known.update(additions)

        if verbose:
            print(f"  Known atoms: {set_text(known)}")


def top_down(kb, query, verbose=True):
    """
    Backward chaining using a leftmost goal selection rule.

    Try clauses in their listed order.
    Replace the selected goal with the clause body.
    Backtrack if a branch fails.
    Succeed when the goal list is empty.

    The assigned knowledge base is acyclic.
    A repeated-goal-state check also avoids exact state cycles.
    """

    def display(depth, message):
        if verbose:
            print("  " * depth + message)

    def prove(goals, active_states, depth):
        goal_text = " & ".join(goals) if goals else "[]"
        display(depth, "Goals: " + goal_text)

        if not goals:
            display(depth, "SUCCESS: empty goal list")
            return True

        if goals in active_states:
            display(depth, "Repeated goal state: backtrack")
            return False

        selected = goals[0]
        remaining = goals[1:]

        applicable = [
            (head, body)
            for head, body in kb
            if head == selected
        ]

        if not applicable:
            display(
                depth,
                f"FAIL: no clause proves {selected}"
            )
            return False

        for head, body in applicable:
            display(
                depth,
                "Try " + clause_text(head, body)
            )

            new_goals = body + remaining

            if prove(
                new_goals,
                active_states | {goals},
                depth + 1,
            ):
                return True

            display(
                depth,
                "Backtrack from " + clause_text(head, body)
            )

        return False

    return prove((query,), frozenset(), 0)


